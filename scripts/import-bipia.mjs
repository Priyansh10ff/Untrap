// Regenerates src/bench/external-bipia.ts from Microsoft's BIPIA benchmark (MIT license):
// https://github.com/microsoft/BIPIA
//
// The external set exists so Untrap can be scored on text nobody on this project wrote or tuned
// against. The selection below is fixed in advance and applies to whole categories, never to
// single samples:
//   attacks: every instruction in benchmark/text_attack_test.json from the 10 categories that tell
//            the AI how to change its reply (encode, translate, add an ad, add a scam link, add
//            misinformation…). The other 5 categories ("Task Automation", "Business
//            Intelligence", "Conversational Agent", "Research Assistance", "Sentiment
//            Analysis") are ordinary questions like "What movies are playing this weekend?":
//            on their own they aren't attacks, so they're left out rather than mislabelled.
//   harmless: the body of every distinct email in benchmark/email/test.jsonl, as visible text.
//            Real emails are full of instructions for people ("Add your withdrawal method"),
//            which makes them good false-alarm tests.
// Attacks are placed the way pages hide them, rotating through five hidden techniques and
// visible text, in file order.
//
//   node scripts/import-bipia.mjs
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const BASE = "https://raw.githubusercontent.com/microsoft/BIPIA/main/benchmark";
const EXCLUDED = new Set(["Task Automation", "Business Intelligence", "Conversational Agent", "Research Assistance", "Sentiment Analysis"]);
const PLACEMENT = ["display-none", "html-comment", "tiny-font", "offscreen", "same-color", "visible"];

const attacks = await (await fetch(`${BASE}/text_attack_test.json`)).json();
const emails = (await (await fetch(`${BASE}/email/test.jsonl`)).text())
  .split("\n")
  .filter(Boolean)
  .map((line) => JSON.parse(line).context);

const rows = [];
let i = 0;
for (const [category, list] of Object.entries(attacks)) {
  if (EXCLUDED.has(category)) continue;
  for (const text of list) {
    const technique = PLACEMENT[i % PLACEMENT.length];
    rows.push({ id: `xa${String(++i).padStart(2, "0")}`, label: "attack", technique, text, note: category });
  }
}
let j = 0;
for (const context of [...new Set(emails)]) {
  const body = context.split("|CONTENT:").pop().replace(/\s+/g, " ").trim();
  rows.push({ id: `xb${String(++j).padStart(2, "0")}`, label: "benign", technique: "visible", text: body, note: "email" });
}

const out = `// Generated by scripts/import-bipia.mjs from Microsoft's BIPIA benchmark. Do not edit by hand.
//
// BIPIA: https://github.com/microsoft/BIPIA
// MIT License. Copyright (c) Microsoft Corporation.
// Permission is hereby granted, free of charge, to any person obtaining a copy of this software
// and associated documentation files (the "Software"), to deal in the Software without
// restriction, including without limitation the rights to use, copy, modify, merge, publish,
// distribute, sublicense, and/or sell copies of the Software, and to permit persons to whom the
// Software is furnished to do so, subject to the following conditions: The above copyright
// notice and this permission notice shall be included in all copies or substantial portions of
// the Software. THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND.
//
// External set: never used to tune Untrap's rules, prompts or policy. If you change Untrap
// because of a miss here, this set stops being a fair test.
import type { Sample } from "./samples.ts";

export const EXTERNAL: Sample[] = ${JSON.stringify(
  rows.map((r) => ({ ...r, hidden: r.technique !== "visible" })),
  null,
  2,
)};
`;
writeFileSync(join(import.meta.dirname, "../src/bench/external-bipia.ts"), out);
console.log(`Wrote ${rows.filter((r) => r.label === "attack").length} attacks and ${rows.filter((r) => r.label === "benign").length} harmless samples.`);
